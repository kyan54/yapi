'use strict';
// Generate the client registry without loading the application, MongoDB, or secrets.
const fs = require('fs');
const path = require('path');
const root = path.resolve(__dirname, '../..');
const configPath = process.env.YAPI_CONFIG || path.resolve(root, '../config.json');
const config = fs.existsSync(configPath) ? JSON.parse(fs.readFileSync(configPath, 'utf8')) : {};
const pluginLib = require('../../common/plugin');
const entries = [];
for (const [items, type] of [[require('../../common/config').exts, 'ext'], [config.plugins, 'plugin']]) {
  for (const plugin of pluginLib.initPlugins(items, type)) {
    if (!plugin.client || !plugin.enable) continue;
    const location = type === 'ext' ? `exts/yapi-plugin-${plugin.name}/client.js` : `yapi-plugin-${plugin.name}/client.js`;
    entries.push(`${JSON.stringify(plugin.name)}: {module: require(${JSON.stringify(location)}), options: ${JSON.stringify(plugin.options || null)}}`);
  }
}
fs.writeFileSync(path.join(root, 'client/plugin-module.js'), `// Generated by scripts/build/plugins.js.\nmodule.exports = {${entries.join(',\n')}};\n`);
module.exports = { versionNotify: config.versionNotify !== false };
